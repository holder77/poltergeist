#!/usr/bin/env bash
#DESCRIPTION: Installs a clickable Poltergeist entry in this Linux user's
#             application menu/launcher (GNOME Activities, KDE's app
#             launcher, most desktop environments' own menus) that asks
#             for root the graphical way - via pkexec, which shows the
#             same native "type your password to continue" dialog every
#             major desktop environment already uses for its own admin
#             prompts - instead of needing a terminal and "sudo" typed by
#             hand every time. This is Linux's closest real equivalent to
#             Windows' own right-click -> "Run as administrator": there is
#             no universal "run as root" checkbox on a Linux file manager
#             the way there is in Windows Explorer, since every desktop
#             environment and distro differs, but a .desktop launcher
#             invoking pkexec is the one approach that works the same way
#             across GNOME, KDE, XFCE, and most others, without needing a
#             distro-specific package.
#
#             This does NOT need to run as root itself - it only WRITES a
#             couple of small files into THIS user's own home folder.
#             Poltergeist itself still asks for root (via the pkexec
#             prompt) every time it's actually launched from the menu
#             entry this creates - that's the whole point.
#
#             Run once, from a normal (non-root) terminal:
#                 bash install_linux_shortcut.sh
#
#             If pkexec isn't available on this box at all (rare, but
#             possible on a minimal/server install with no desktop
#             environment installed), this says so plainly and leaves the
#             plain terminal fallback - "sudo python3 poltergeist.py",
#             documented in the main README - as the way to run it
#             instead, rather than installing a broken shortcut.

#Stop immediately on any unexpected error, rather than silently leaving a
#half-written shortcut behind.
set -euo pipefail

#Work out the real, absolute path of the repo root (two folders up from
#this script's own location: packaging/linux/install_linux_shortcut.sh ->
#repo root), the same "resolve relative to myself, not the caller's
#current directory" approach poltergeist.py's own launcher already uses.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
POLTERGEIST_PY="${REPO_ROOT}/poltergeist.py"

#Bail out plainly, rather than install something broken, if this doesn't
#actually look like the Poltergeist repo (someone moved this script on
#its own, say).
if [ ! -f "${POLTERGEIST_PY}" ]; then
    echo "Could not find poltergeist.py at ${POLTERGEIST_PY} - is this script still"
    echo "sitting inside the Poltergeist repo's packaging/linux/ folder?"
    exit 1
fi

#pkexec is what actually shows the graphical "enter your password"
#prompt - without it, there is nothing for the shortcut this script would
#create to actually run, so check for it up front and say so plainly
#instead of writing a launcher that would just fail silently when clicked.
if ! command -v pkexec >/dev/null 2>&1; then
    echo "pkexec was not found on this machine - a graphical 'run as root'"
    echo "shortcut isn't possible here (this is common on a minimal/server"
    echo "install with no desktop environment's PolicyKit agent installed)."
    echo
    echo "Poltergeist still works fine from a terminal instead:"
    echo "    sudo python3 \"${POLTERGEIST_PY}\""
    exit 1
fi

#pkexec also needs python3 itself by its own FULL path, not just found on
#PATH - its own restricted environment doesn't reliably inherit the
#calling shell's PATH the way sudo does.
PYTHON3_PATH="$(command -v python3)"
if [ -z "${PYTHON3_PATH}" ]; then
    echo "Could not find python3 on PATH - install Python 3 first."
    exit 1
fi

#Build a small wrapper script (not a raw pkexec call straight in the
#.desktop file) specifically so it can pass this user's own DISPLAY and
#XAUTHORITY through to the elevated process - pkexec deliberately starts
#the program it runs with a near-EMPTY environment for security, which
#means a GUI app launched through it, with no further help, fails to
#find an X11/Wayland display to open a window on at all. Forwarding
#these two variables explicitly is the standard, documented way around
#that, and is exactly what this wrapper exists to do.
LAUNCHER_PATH="${SCRIPT_DIR}/poltergeist-launch.sh"
cat > "${LAUNCHER_PATH}" <<EOF
#!/usr/bin/env bash
#Auto-generated by install_linux_shortcut.sh - re-run that script to
#rebuild this file if Poltergeist is ever moved to a different folder.
exec pkexec env DISPLAY="\${DISPLAY:-}" XAUTHORITY="\${XAUTHORITY:-\${HOME}/.Xauthority}" \\
    "${PYTHON3_PATH}" "${POLTERGEIST_PY}" "\$@"
EOF
chmod +x "${LAUNCHER_PATH}"
echo "Wrote ${LAUNCHER_PATH}"

#Write the actual .desktop launcher - the file a GNOME/KDE/XFCE menu
#actually reads to show a clickable application entry. Installed per-user
#(no root needed to write it, and no root needed to run this install
#script itself) under the standard freedesktop.org location every major
#desktop environment already scans automatically.
APPLICATIONS_DIR="${HOME}/.local/share/applications"
mkdir -p "${APPLICATIONS_DIR}"
DESKTOP_FILE="${APPLICATIONS_DIR}/poltergeist.desktop"
cat > "${DESKTOP_FILE}" <<EOF
[Desktop Entry]
Type=Application
Name=Poltergeist
Comment=Blue team audit tool - never kills a process, never deletes evidence
Exec=${LAUNCHER_PATH}
Terminal=false
Categories=System;Security;
EOF
echo "Wrote ${DESKTOP_FILE}"

echo
echo "Done. Poltergeist should now show up in your application menu/launcher -"
echo "clicking it will show the normal 'enter your password to continue' prompt"
echo "every time, then start Poltergeist already running as root."
echo
echo "(If it doesn't show up right away, some desktop environments only"
echo "re-scan their menu occasionally - logging out and back in always works.)"
